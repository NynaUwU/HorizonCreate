#!/usr/bin/env python3
"""Copies the engine crates into the native bundle as modules.

Native bundles may not have path dependencies (docs/native-mods.md, "The mod's
crate"), so `native/api/src/engine/` holds copies of `kinetics` and `hcglue`.
Never edit the copies: edit the crates and run this again.

    python3 tools/sync_native.py
"""
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DST = ROOT / "native/api/src/engine"
HEADER = "// @generated by tools/sync_native.py from {src}; edit the original.\n"


def copy(src, dst, rewrite=lambda s: s):
    text = (ROOT / src).read_text()
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(HEADER.format(src=src) + rewrite(text))


def main():
    shutil.rmtree(DST, ignore_errors=True)
    for f in ("network.rs", "placement.rs", "presets.rs"):
        copy(f"kinetics/src/{f}", DST / "kinetics" / f)
    copy("kinetics/src/lib.rs", DST / "kinetics" / "mod.rs")
    rewrite = lambda s: s.replace("use kinetics::", "use super::kinetics::")
    for src in sorted((ROOT / "hcglue/src").glob("*.rs")):
        dst = "mod.rs" if src.name == "lib.rs" else src.name
        copy(f"hcglue/src/{src.name}", DST / "hcglue" / dst, rewrite)
    (DST / "mod.rs").write_text(HEADER.format(src="tools/sync_native.py")
                                + "#![allow(dead_code, unused_imports)]\npub mod hcglue;\npub mod kinetics;\n")
    print(f"synced -> {DST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
